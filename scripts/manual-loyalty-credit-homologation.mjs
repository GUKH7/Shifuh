import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createClient } from "@supabase/supabase-js";
const url=process.env.NEXT_PUBLIC_SUPABASE_URL, key=process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if(process.env.MANUAL_LOYALTY_LOCAL_E2E!=="1" || !url || !key || !["localhost","127.0.0.1"].includes(new URL(url).hostname)) throw Error("Requires isolated local Supabase");
const make=async()=>{
 const c=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
 const {data,error}=await c.auth.signInWithPassword({email:process.env.E2E_ADMIN_EMAIL,password:process.env.E2E_ADMIN_PASSWORD});
 assert.ifError(error);assert.ok(data.user);return {c,user:data.user};
};
const a=await make(),b=await make();
const customer="44444444-4444-4444-8444-444444444444";
const foreign="bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
const query=()=>a.c.from("loyalty_accounts").select("points_balance").eq("customer_id",customer).single();
const before=await query();assert.ifError(before.error);
const rpc=(c,id,customerId=customer,amount=7,reason="Almoço presencial")=>c.rpc("credit_loyalty_points_manual",{p_customer_id:customerId,p_request_id:id,p_mode:"points",p_amount:amount,p_reason:reason});
const key1=randomUUID();
const results=await Promise.all([rpc(a.c,key1),rpc(b.c,key1)]);
results.forEach(r=>assert.ifError(r.error));
assert.deepEqual(results.map(r=>r.data[0].was_duplicate).sort(),[false,true]);
const after=await query();assert.ifError(after.error);
assert.equal(Number(after.data.points_balance),Number(before.data.points_balance)+7);
const replay=await rpc(a.c,key1);assert.ifError(replay.error);assert.equal(replay.data[0].was_duplicate,true);
const changed=await rpc(a.c,key1,customer,8);assert.ok(changed.error);
const foreignAttempt=await rpc(a.c,randomUUID(),foreign);assert.ok(foreignAttempt.error);
const anon=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
assert.ok((await rpc(anon,randomUUID())).error);
const [otherA,otherB]=await Promise.all([rpc(a.c,randomUUID(),customer,4),rpc(b.c,randomUUID(),customer,5)]);
assert.ifError(otherA.error);assert.ifError(otherB.error);
const end=await query();assert.ifError(end.error);
assert.equal(Number(end.data.points_balance),Number(before.data.points_balance)+16);
const audit=await a.c.from("loyalty_point_transactions").select("points_delta,metadata,idempotency_key").eq("customer_id",customer).eq("idempotency_key","manual:"+key1);
assert.ifError(audit.error);assert.equal(audit.data.length,1);
assert.equal(audit.data[0].metadata.actor_user_id,a.user.id);
console.log("Manual loyalty credit local homologation passed");
